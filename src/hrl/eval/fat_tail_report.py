"""Auto-assembled fat-tail robustness report (spec section 6, "Report artifact").

`write_fat_tail_report(results, out_dir)` collates the per-mechanism T-test tables into
`results/FAT_TAIL_REPORT.md`. Mechanisms 1 (bounded influence), 4 (conformal bands) and 5
(leverage) are wired here; mechanisms 2 (adaptive R, Phase 4) and 3 (changepoint, Phase 6) are
owned by concurrent phases and are rendered as PENDING placeholders until their modules land.

`results` is a flexible dict keyed by mechanism tag ("mech1", "mech4", "mech5", ...). Each value
is a dict of {row_label: dict_of_columns}. The renderer emits whatever is present and marks the
rest pending, so a partial run still produces a valid report.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

_SECTIONS: list[tuple[str, str, str]] = [
    ("mech1", "Mechanism 1 -- Bounded-influence state update (WoLF / Student-t)",
     "T1 influence saturation, T2 contamination sweep, T3 paired Wilcoxon, T4 efficiency."),
    ("mech2", "Mechanism 2 -- Robust adaptive R_t",
     "T7-T9. PENDING: owned by Phase 4 (filters/stages/adaptive_r.py)."),
    ("mech3", "Mechanism 3 -- Clustered extremes: break vs outlier",
     "T10-T14. PENDING: owned by Phase 6 (filters/stages/changepoint.py)."),
    ("mech4", "Mechanism 4 -- Conformal (ACI) calibration of trading bands",
     "T15 unconditional coverage (Kupiec), T16 conditional coverage (Christoffersen)."),
    ("mech5", "Mechanism 5 -- Leverage points (extremes in the regressor)",
     "T20 leverage-damage gate on S7 / S7b."),
]


def _render_table(rows: dict[str, dict[str, Any]]) -> str:
    """Render a {label: {col: val}} mapping as a GitHub markdown table."""
    if not rows:
        return "_no rows_\n"
    cols: list[str] = []
    for r in rows.values():
        for k in r:
            if k not in cols:
                cols.append(k)
    header = "| metric | " + " | ".join(cols) + " |\n"
    sep = "|" + "---|" * (len(cols) + 1) + "\n"
    body = ""
    for label, r in rows.items():
        cells = []
        for c in cols:
            v = r.get(c, "")
            cells.append(f"{v:.4g}" if isinstance(v, float) else str(v))
        body += f"| {label} | " + " | ".join(cells) + " |\n"
    return header + sep + body


def write_fat_tail_report(results: dict[str, Any], out_dir: str | Path = "results") -> Path:
    """Write FAT_TAIL_REPORT.md under `out_dir`; return the path.

    `results` may contain any subset of {"mech1", "mech4", "mech5", ...}. Missing mechanisms
    render as PENDING (mechs 2 and 3 always pending until Phases 4/6 land).
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [
        "# Fat-Tail Robustness Layer -- Test Report",
        "",
        "Auto-generated by `hrl.eval.fat_tail_report.write_fat_tail_report`. "
        "See `docs/FAT_TAIL_SPEC.md` for the mechanism and test definitions.",
        "",
    ]
    for tag, title, blurb in _SECTIONS:
        lines.append(f"## {title}")
        lines.append("")
        lines.append(f"_{blurb}_")
        lines.append("")
        rows = results.get(tag)
        if rows:
            lines.append(_render_table(rows))
        else:
            pending = tag in ("mech2", "mech3")
            note = ("TODO -- depends on a concurrent phase; not runnable in this branch."
                    if pending else "TODO -- results not supplied to this run.")
            lines.append(f"> {note}")
            lines.append("")
    report = "\n".join(lines).rstrip() + "\n"
    path = out / "FAT_TAIL_REPORT.md"
    path.write_text(report)
    return path
